"""Regression gate.

Fails the build when quality drops below the committed baseline.

**The scenario this exists to prevent:** a prompt is tweaked on Tuesday to improve one
kind of answer, it quietly degrades another, and nobody notices until Friday from a
customer. With this gate, the change fails CI on Tuesday.

**Why it runs on stored results rather than calling the API.** Re-generating fifty
answers and re-judging them costs tokens on every build, which on a free tier means the
gate either bankrupts the quota or gets disabled. Instead the gate reads
`evals/faithfulness_v2.jsonl`, which is regenerated by the pipeline whenever anything
that affects it changes — the prompt text is part of the LLM cache key, so editing a
prompt invalidates exactly the cached calls it affects and nothing else.

Free when nothing changed. Correct when something did.

**Why the thresholds are relative.** The generator is non-deterministic even at
temperature 0, so scores wobble between runs. A gate that fires on noise gets switched
off, which is worse than having no gate. Tolerance is 5% of the baseline: tight enough
to catch a real regression, loose enough to survive jitter.

**Why prompt versions are checked separately.** A score produced under a different
prompt is not comparable to the baseline. The gate distinguishes "quality dropped" from
"the prompt changed, re-baseline deliberately" rather than conflating them.

Run with:  uv run pytest tests/test_regression.py -v
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
BASELINE_PATH = ROOT / "results" / "baseline.json"
SCORES_PATH = ROOT / "evals" / "faithfulness_v2.jsonl"
ANSWERS_PATH = ROOT / "evals" / "answers_v2.jsonl"
PROMPTS_DIR = ROOT / "prompts"


def load_jsonl(path: Path) -> list[dict]:
    with open(path, "r", encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


@pytest.fixture(scope="module")
def baseline() -> dict:
    if not BASELINE_PATH.exists():
        pytest.skip(
            f"no baseline at {BASELINE_PATH} — run scripts/write_baseline.py"
        )
    return json.loads(BASELINE_PATH.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def scores() -> list[dict]:
    if not SCORES_PATH.exists():
        pytest.skip(
            f"no scores at {SCORES_PATH} — run scripts/phase7_score_all.py"
        )
    return load_jsonl(SCORES_PATH)


@pytest.fixture(scope="module")
def answers() -> list[dict]:
    if not ANSWERS_PATH.exists():
        pytest.skip(f"no answers at {ANSWERS_PATH}")
    return load_jsonl(ANSWERS_PATH)


# ---------------------------------------------------------------------------
# The gate itself
# ---------------------------------------------------------------------------


class TestQualityGate:
    def test_faithfulness_has_not_regressed(self, baseline, scores):
        """The headline metric, within tolerance of the baseline."""
        expected = baseline["metrics"]["faithfulness"]
        tolerance = baseline["tolerance"]
        floor = expected * (1 - tolerance)

        actual = sum(r["faithful"] for r in scores) / len(scores)

        assert actual >= floor, (
            f"faithfulness {actual:.4f} is below the floor {floor:.4f} "
            f"(baseline {expected:.4f}, tolerance {tolerance:.0%}).\n"
            f"Either quality regressed, or the change was intended and the baseline "
            f"needs updating with scripts/write_baseline.py."
        )

    def test_unanswerable_cases_still_handled(self, baseline, scores):
        """Refusing when no answer exists is the behaviour most worth protecting.

        Separated from the headline because it is the property a prompt change is
        most likely to break: loosening the refusal instruction improves answers on
        easy questions and silently starts hallucinating on impossible ones. The
        aggregate can stay flat while this collapses.
        """
        unanswerable = [r for r in scores if not r["answerable"]]
        if not unanswerable:
            pytest.skip("no unanswerable cases in the score set")

        expected = baseline["metrics"].get("faithfulness_unanswerable")
        if expected is None:
            pytest.skip("baseline has no unanswerable figure")

        actual = sum(r["faithful"] for r in unanswerable) / len(unanswerable)
        floor = expected * (1 - baseline["tolerance"])

        assert actual >= floor, (
            f"faithfulness on unanswerable questions {actual:.4f} is below "
            f"{floor:.4f}. The system has started answering questions it cannot "
            f"answer — check whether the refusal instruction in prompts/v1/qa.yaml "
            f"was weakened."
        )

    def test_retrieval_has_not_regressed(self, baseline, answers):
        """Mean retrieval recall over the golden set.

        Retrieval and generation are gated separately because they fail separately —
        Phase 7 measured faithfulness as independent of retrieval quality. A single
        combined number would hide a retrieval regression behind a stable generation
        score.
        """
        expected = baseline["metrics"]["mean_retrieval_recall_10"]
        answerable = [a for a in answers if a["answerable"]]
        actual = sum(a["retrieval_recall_10"] for a in answerable) / len(answerable)
        floor = expected * (1 - baseline["tolerance"])

        assert actual >= floor, (
            f"mean retrieval recall {actual:.4f} is below {floor:.4f} "
            f"(baseline {expected:.4f}). Retrieval regressed, not generation."
        )


# ---------------------------------------------------------------------------
# Comparability — is this score even measuring the same thing?
# ---------------------------------------------------------------------------


class TestComparability:
    def test_prompt_version_matches_baseline(self, baseline):
        """A score under a different prompt is not comparable to the baseline.

        This fails loudly on a prompt change rather than letting the quality
        assertions compare two different measurements. The fix is deliberate
        re-baselining, not loosening the tolerance.
        """
        import yaml

        for name, recorded in baseline["prompts"].items():
            path = PROMPTS_DIR / recorded["version"] / f"{name}.yaml"
            assert path.exists(), (
                f"baseline references {path}, which does not exist"
            )
            data = yaml.safe_load(path.read_text(encoding="utf-8"))
            assert str(data.get("version")) == recorded["version"], (
                f"{name}.yaml declares version {data.get('version')} but the "
                f"baseline expects {recorded['version']}"
            )

    def test_judge_model_matches_baseline(self, baseline, scores):
        """The calibration applies to one judge model.

        Swapping the judge invalidates kappa 0.87 — the new model has not been
        measured against human labels, so its scores carry no warrant.
        """
        expected = baseline["config"]["judge_model"]
        used = {r["judge_model"] for r in scores}
        assert used == {expected}, (
            f"scores were produced by {used}, baseline expects {expected}. "
            f"The calibration does not transfer between judge models — re-run "
            f"scripts/phase7_calibrate.py before trusting these scores."
        )

    def test_judge_prompt_version_matches(self, baseline, scores):
        expected = baseline["prompts"]["judge_faithfulness"]["version"]
        used = {r.get("judge_prompt_version") for r in scores}
        assert used == {expected}, (
            f"scores used judge prompt {used}, baseline expects {expected}. "
            f"Cohen's kappa was measured against one rubric; a different rubric "
            f"needs re-calibrating."
        )

    def test_every_answer_was_scored(self, answers, scores):
        """A partial score set would quietly change the denominator."""
        answer_ids = {a["id"] for a in answers}
        score_ids = {s["id"] for s in scores}
        missing = answer_ids - score_ids
        assert not missing, (
            f"{len(missing)} answers have no faithfulness score: "
            f"{sorted(missing)[:5]}"
        )


# ---------------------------------------------------------------------------
# Integrity — the evaluation data itself
# ---------------------------------------------------------------------------


class TestEvalDataIntegrity:
    def test_golden_set_has_unanswerable_cases(self):
        """Without them a faithfulness metric has nothing to catch.

        Phase 6 found the generator refuses on 88% of retrieval failures, so a golden
        set of answerable questions alone would report near-perfect faithfulness and
        miss the condition where the system actually hallucinates.
        """
        golden = ROOT / "evals" / "golden_v2.jsonl"
        if not golden.exists():
            pytest.skip("no golden set")
        rows = load_jsonl(golden)
        unanswerable = [r for r in rows if not r["answerable"]]
        assert len(unanswerable) >= 5, (
            f"only {len(unanswerable)} unanswerable cases — the set cannot detect "
            f"hallucination on impossible questions"
        )

    def test_human_labels_are_not_one_sided(self):
        """Kappa is uninformative on a one-sided label distribution.

        If every case is faithful, both raters say yes to everything, expected
        agreement by chance approaches 100%, and kappa collapses toward zero despite
        perfect agreement — the kappa paradox.
        """
        labels_path = ROOT / "evals" / "human_labels_v1.jsonl"
        if not labels_path.exists():
            pytest.skip("no human labels")
        labels = [r["faithful"] for r in load_jsonl(labels_path)]
        faithful_rate = sum(labels) / len(labels)
        assert 0.2 <= faithful_rate <= 0.8, (
            f"human labels are {faithful_rate:.0%} faithful — too one-sided for "
            f"kappa to be informative. Re-stratify the labelling set."
        )

    def test_calibration_is_recorded(self, baseline):
        """A faithfulness score without its calibration is an unvalidated opinion."""
        cal = baseline.get("calibration", {})
        assert "cohens_kappa" in cal, "baseline records no kappa"
        assert cal["cohens_kappa"] >= 0.6, (
            f"kappa {cal['cohens_kappa']} is below 0.6. The judge is not reliable "
            f"enough for its scores to be reported without qualification."
        )
        assert cal.get("human_labels", 0) >= 20, (
            "fewer than 20 human labels — the interval would be too wide to be useful"
        )
